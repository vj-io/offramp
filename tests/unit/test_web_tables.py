"""The dashboard says what the PR says. web/lib/offramp-tables.json mirrors the PR writer's sentence tables
(and the pipeline's not-evaluated log line); web/lib/offramp-cases.json holds the PR writer's own output for
a spread of manual-review failures and kept verdicts, which web/lib/format.test.ts replays through the
TypeScript port, so the joining text is guarded too. Regenerate both with UPDATE_SNAPSHOTS=1."""

import json
import os
from itertools import product
from pathlib import Path
from types import SimpleNamespace
from typing import get_args

from offramp import pipeline
from offramp.agents import pr_writer
from offramp.evals.scorers.aggregate import JUDGE_CASE_FLOOR, JUDGE_FLOOR
from offramp.schemas import Gate, PatchFailure, PatchFailureKind, Verdict

WEB = Path(__file__).resolve().parents[2] / "web" / "lib"
WEB_HANDLES_ITSELF = {"budget", "threshold", "judge_mean", "case_floor"}  # in format.ts keptText
NOTE = "Generated by tests/unit/test_web_tables.py from offramp/ (UPDATE_SNAPSHOTS=1); do not edit by hand."


def tables() -> dict:
    return {
        "_note": NOTE,
        "cause": pr_writer._CAUSE,
        "alone": pr_writer._ALONE,
        "ended": pr_writer._ENDED,
        "missed": pr_writer._MISSED,
        "price_methods": pr_writer.PRICE_METHODS,
        "judge_floor": JUDGE_FLOOR,
        "judge_case_floor": JUDGE_CASE_FLOOR,
        "bounds": pr_writer.BOUNDS,
        "not_evaluated": pipeline.NOT_EVALUATED,
    }


# Names with $&, $1, $$ and $' as well as plain ones: JavaScript's replace() would read those as patterns.
VARIANTS = [
    ([], []),
    (["tests/t.py"], ["t.py::test_a"]),
    (["b $& c.py", "d$1$$.py", "e$'f.py"], ["t.py::test_$&x"]),
]
LASTS = [None, "checks_failed", "deletes_tests", "search_miss", "probe_mismatch", "backstop", "repo_red"]


def manual_cases() -> list[dict]:
    out = []
    for kind in get_args(PatchFailureKind):
        ended = kind in pr_writer._ENDED
        for i, (last, model_edit, (files, tests)) in enumerate(
            product(LASTS if ended else [None], [True, False], VARIANTS)
        ):
            failure = {"kind": kind, "last": last, "tries": [0, 1, 3][i % 3] if ended else 0}
            failure |= {"model_edit": model_edit, "files": files, "tests": tests}
            v = Verdict(site_id="cs_01", decision="MANUAL_REVIEW", reason="raw | output",
                        patch_failure=PatchFailure(**failure))  # fmt: skip
            out.append({"failure": failure, "reason": v.reason, "expected": list(pr_writer.manual_reason(v))})
    return out


def kept_cases() -> list[dict]:
    """_kept for the tasks whose figure the web writes as the PR does (free text has its own format there)."""
    figures = [
        {"parity_pct": 71.4, "holdout_cases": 7, "holdout_passed": 5, "parity_lower_pct": 35.9},
        {"parity_pct": 71.4},  # recorded before the bounds
        {"parity_pct": None},
    ]
    out = []
    tasks = ["classification", "reasoning", "json_extraction"]
    for task, gate, fig in product(tasks, [None, *get_args(Gate)], figures):
        if gate in ("judge_mean", "case_floor"):
            continue  # free-text gates
        v = Verdict(site_id="cs_05", decision="KEEP_CLOSED", reason="r", failed_gate=gate, **fig)
        site = SimpleNamespace(contract=SimpleNamespace(task_type=task))
        bar = f"{(0.9 if task == 'reasoning' else 0.95) * 100:g}%"
        verdict = {"failed_gate": gate, **fig}
        out.append({"verdict": verdict, "task": task, "expected": pr_writer._kept(v, site, bar)})
    return out


def check(name: str, value: dict, indent: int | None = 1) -> None:
    path = WEB / name
    text = json.dumps(value, indent=indent, ensure_ascii=False) + "\n"
    if os.environ.get("UPDATE_SNAPSHOTS"):
        path.write_text(text, encoding="utf-8")
    assert path.read_text(encoding="utf-8") == text, f"{name} is out of date: rerun with UPDATE_SNAPSHOTS=1"


def test_the_web_tables_equal_the_pr_writers():
    check("offramp-tables.json", tables())


def test_the_web_cases_are_the_pr_writers_own_output():
    cases = {"_note": NOTE, "manual_reason": manual_cases(), "kept": kept_cases()}
    check("offramp-cases.json", cases, indent=None)


def test_every_recorded_kind_and_gate_has_words_on_the_web():
    web = json.loads((WEB / "offramp-tables.json").read_text(encoding="utf-8"))
    assert set(get_args(PatchFailureKind)) == set(web["cause"]) | set(web["ended"])
    assert set(get_args(Gate)) == set(web["missed"]) | WEB_HANDLES_ITSELF
